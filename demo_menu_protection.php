// Имитация проверки
function checkIfMenuCommand($input) {
    $menuCommands = [
        '📊 Табель', 'Табель',
        '❓ Помощь', 'Помощь',
        '👤 Профиль', 'Профиль',
        '📁 Проекты', 'Проекты',
        '⚙️ Админка', 'Админка',
        '🔐 Запросить доступ', 'Запросить доступ',
        '🛠️ Управление проектом', 'Управление проектом',
        '📋 Супервайзер', 'Супервайзер'
    ];
    
    return in_array($input, $menuCommands);
}

// Тестовые данные
$testCases = [
    // Нормальные названия проектов
    ['input' => 'ОИ834', 'type' => 'normal', 'description' => 'Обычный шифр проекта'],
    ['input' => 'БКНС-115', 'type' => 'normal', 'description' => 'Проект с дефисом'],
    ['input' => 'TEST2024', 'type' => 'normal', 'description' => 'Проект с цифрами'],
    
    // Случайные нажатия меню
    ['input' => '📊 Табель', 'type' => 'menu', 'description' => 'Кнопка главного меню'],
    ['input' => 'Профиль', 'type' => 'menu', 'description' => 'Текстовая команда меню'],
    ['input' => '⚙️ Админка', 'type' => 'menu', 'description' => 'Кнопка админки'],
];

echo "🧪 ТЕСТОВЫЕ СЛУЧАИ:\n";
echo "══════════════════════════════════════════════════════════════\n\n";

foreach ($testCases as $index => $test) {
    $num = $index + 1;
    $input = $test['input'];
    $desc = $test['description'];
    
    $isMenuCommand = checkIfMenuCommand($input);
    
    echo "Тест #{$num}: {$desc}\n";
    echo "├─ Ввод: '{$input}'\n";
    
    if ($isMenuCommand) {
        echo "├─ Результат: ❌ ЗАБЛОКИРОВАНО (команда меню)\n";
        echo "├─ Действия:\n";
        echo "│  ├─ Очистка state: project_mod_action = null\n";
        echo "│  ├─ Сообщение: ⚠️ Ввод отменён\n";
        echo "│  └─ Перенаправление в меню\n";
        echo "└─ Проект создан: НЕТ ✅\n";
    } else {
        echo "├─ Результат: ✅ РАЗРЕШЕНО (валидное название)\n";
        echo "├─ Действия:\n";
        echo "│  ├─ Валидация названия\n";
        echo "│  ├─ Создание проекта в БД\n";
        echo "│  └─ Уведомление администраторов\n";
        echo "└─ Проект создан: ДА ✅\n";
    }
    
    echo "\n";
}

echo "══════════════════════════════════════════════════════════════\n";
echo "📊 СТАТИСТИКА:\n\n";

$totalTests = count($testCases);
$normalInputs = array_filter($testCases, fn($t) => $t['type'] === 'normal');
$menuInputs = array_filter($testCases, fn($t) => $t['type'] === 'menu');

echo "Всего тестов:           {$totalTests}\n";
echo "Нормальные названия:    " . count($normalInputs) . " (разрешены ✅)\n";
echo "Команды меню:           " . count($menuInputs) . " (заблокированы ❌)\n\n";

echo "══════════════════════════════════════════════════════════════\n";
echo "💡 ПОЯСНЕНИЕ РАБОТЫ:\n\n";

echo "1️⃣  Пользователь начинает добавление проекта\n";
echo "    └─ Устанавливается state: project_mod_action = 'add_new'\n\n";

echo "2️⃣  Система запрашивает название проекта\n";
echo "    └─ Ожидает текстовый ввод от пользователя\n\n";

echo "3️⃣  Пользователь вводит текст ИЛИ нажимает кнопку меню\n";
echo "    └─ Срабатывает GenericmessageCommand::execute()\n\n";

echo "4️⃣  Проверка: является ли ввод командой меню?\n";
echo "    ├─ ✅ ДА  → Очистка state, сообщение, перенаправление\n";
echo "    └─ ❌ НЕТ → Валидация названия, создание проекта\n\n";

echo "══════════════════════════════════════════════════════════════\n";
echo "🎯 ПРЕИМУЩЕСТВА:\n\n";

$benefits = [
    "Защита от случайных ошибок пользователей",
    "Чистая база данных без 'мусорных' проектов",
