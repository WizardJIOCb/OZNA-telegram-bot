<?php
/**
 * Полный тест формата для всех типов текущей деятельности
 */

echo "=== ПОЛНЫЙ ТЕСТ ФОРМАТА ТЕКУЩЕЙ ДЕЯТЕЛЬНОСТИ ===\n\n";

// Тестовые данные
$fio = "Петров Петр Петрович";
$date = "13.10.2025";

// Все типы текущей деятельности
$currentActivityTypes = [
    'МедОсмотр' => '👨‍⚕️ Медицинский осмотр',
    'Аттестация' => '📚 Аттестация', 
    'ПодготовкаТКП' => '🏢 Подготовка ТКП',
    'Общая' => '📊 Общая деятельность'
];

echo "Новый формат для всех типов текущей деятельности:\n";
echo str_repeat("=", 60) . "\n";

foreach ($currentActivityTypes as $activityType => $activityText) {
    $message = sprintf(
        "<b>%s</b>\r\n✅Запись в табель от <b>%s</b>: Текущая деятельность (<b>%s</b>) добавлена",
        $fio,
        $date,
        $activityText
    );
    
    echo "\n{$activityType}:\n";
    echo $message . "\n";
}

echo "\n" . str_repeat("=", 60) . "\n";
echo "✅ Все типы текущей деятельности теперь имеют единый формат!\n";
echo "📝 Формат: 'Текущая деятельность (Конкретный вид)' делает отчеты более понятными.\n";