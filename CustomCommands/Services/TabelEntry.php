        if (in_array($activityType, ['ПодготовкаТКП_ОПНВГ', 'ПодготовкаТКП_НКО', 'ПодготовкаТКП_МСО', 'ПодготовкаТКП_АСН'])) {
            return sprintf(
                "Проект <b>%s</b>: <b>%s</b>. Отправить запись в табель?",
                $projectCode,
                $activityName
            );
        }
        
        // Special handling for mobile brigade other activity
        if ($activityType === 'МобБриг_ПрочаяДеятельность') {
            return sprintf(
                "Прочая деятельность (Мобильная бригада), отправить запись в табель в проект <b>%s</b>?",
                $projectCode
            );
        }
        
        return sprintf(
            "<b>%s</b>, отправить запись в табель в проект <b>%s</b>?",
            $activityName,
            $projectCode
        );
    }

