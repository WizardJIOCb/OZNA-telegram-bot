/**
 * Debug the actual callback flow to find why parent category is missing
 */

echo "🔍 Debugging actual callback flow\n";
echo "=================================\n\n";

// Let's trace the exact flow:
// 1. User clicks "Простой" → goes to main categories
// 2. User clicks "Допоставка" → callback would be "category_Табель_Простой_1"
// 3. User clicks "Дефицит по спецификации" → callback would be "category_Табель_Простой_1_def"

echo "Expected callback scenarios:\n";
echo "1. Full hierarchy: category_Табель_Простой_1_def\n";
echo "2. Direct access: category_Табель_Простой_def\n\n";

// Test both scenarios with exact callback parsing logic
function testActualCallback(string $callback): void
{
    echo "Testing callback: '{$callback}'\n";
    
    // Parse exactly like the real method
    $parts = explode('_', str_replace('category_Табель_', '', $callback));
    echo "Parts: " . json_encode($parts) . "\n";
    
    $categories = [
        '1' => 'Ожидание допоставки',
        '2' => 'Отсутствие обратной связи'
    ];
    
    $subcategoryToParent = [
        'def' => ['parent' => '1', 'text' => 'Дефицит по спецификации'],
        'ost' => ['parent' => '1', 'text' => 'Отсутствие в поставке']
    ];
    
    $reason = '';
    
    // Skip supervision prefix if present
    $startIndex = ($parts[0] === 'ШМ' && $parts[1] === 'Простой') ? 2 : 1;
    echo "Start index: {$startIndex}\n";
    
    // Extract the relevant parts
    $categoryNum = isset($parts[$startIndex]) ? $parts[$startIndex] : null;
    $subcategoryKey = isset($parts[$startIndex + 1]) ? $parts[$startIndex + 1] : null;
    $subSubcategoryKey = isset($parts[$startIndex + 2]) ? $parts[$startIndex + 2] : null;
    
    echo "Initial - categoryNum: '{$categoryNum}', subcategoryKey: '{$subcategoryKey}'\n";
    
    // Special case: If categoryNum looks like a subcategory key, treat it as such
    if ($categoryNum && !isset($categories[$categoryNum]) && isset($subcategoryToParent[$categoryNum])) {
        echo "Detected direct subcategory access!\n";
        $subSubcategoryKey = $subcategoryKey;
        $subcategoryKey = $categoryNum;
        $categoryNum = null;
        echo "After shift - categoryNum: '{$categoryNum}', subcategoryKey: '{$subcategoryKey}'\n";
    }
    
    // If we have a category number, use it
    if ($categoryNum && isset($categories[$categoryNum])) {
        $reason = $categories[$categoryNum];
        echo "Found main category: '{$reason}'\n";
    }
    // If no category number but we have a subcategory, look up its parent
    elseif ($subcategoryKey && isset($subcategoryToParent[$subcategoryKey])) {
        $parentCategoryNum = $subcategoryToParent[$subcategoryKey]['parent'];
        if ($parentCategoryNum && isset($categories[$parentCategoryNum])) {
            $reason = $categories[$parentCategoryNum];
            echo "Found parent category via reverse lookup: '{$reason}'\n";
        }
    }
    
    // Add subcategory
    if ($subcategoryKey && isset($subcategoryToParent[$subcategoryKey])) {
        $subcategoryText = $subcategoryToParent[$subcategoryKey]['text'];
        if (!empty($reason)) {
            if ($subSubcategoryKey && isset($subcategoryToParent[$subSubcategoryKey])) {
                $reason .= ' → ' . $subcategoryText;
            } else {
                $reason .= ' (' . $subcategoryText . ')';
            }
        } else {
            $reason = $subcategoryText;
        }
        echo "Added subcategory: '{$subcategoryText}', final reason: '{$reason}'\n";
    }
    
    $finalReason = $reason ?: 'Простой';
    echo "FINAL RESULT: '{$finalReason}'\n";
    echo "---\n\n";
}

// Test the scenarios
testActualCallback('category_Табель_Простой_1_def');
testActualCallback('category_Табель_Простой_def');

echo "💡 If both tests show correct results but the bot still shows wrong result,\n";
echo "   the issue might be in which callback is actually being generated by the menu system.\n";