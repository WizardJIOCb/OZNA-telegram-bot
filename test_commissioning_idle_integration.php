// This would be called by handleIdleFinalSelection
function simulateCommissioningIdleProcessing($category) {
    echo "Input callback: {$category}\n";
    
    // Parse callback
    $parts = explode('_', str_replace('category_Табель_', '', $category));
    echo "Parsed parts: " . json_encode($parts) . "\n";
    
    // Extract components
    $startIndex = 1; // Skip "Простой"
    $categoryNum = $parts[$startIndex] ?? null;
    $subcategoryKey = $parts[$startIndex + 1] ?? null;
    
    echo "Category number: {$categoryNum}\n";
    echo "Subcategory key: {$subcategoryKey}\n";
    
    // Apply commissioning logic
    $parentCategories = ['1' => 'Ожидание допоставки'];
    $subcategories = ['def' => ['parent' => '1', 'text' => 'Дефицит по спецификации']];
    
    if (isset($subcategories[$subcategoryKey])) {
        $subcategoryData = $subcategories[$subcategoryKey];
        $parentText = $parentCategories[$subcategoryData['parent']];
        $subcategoryText = $subcategoryData['text'];
        $result = $parentText . ' (' . $subcategoryText . ')';
        echo "Commissioning format applied: {$result}\n";
        return $result;
    }
    
    return 'Простой';
}

