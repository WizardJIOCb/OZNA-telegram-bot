try {
    // Инициализация сервисов
    echo "1. Инициализация сервисов...\n";
    $messageService = new MessageService();
    $databaseService = new DatabaseService();
    echo "✅ Сервисы инициализированы успешно\n\n";
    
    // Получение списка пользователей
    echo "2. Получение списка российских пользователей...\n";
    $allUsers = $databaseService->getAllUsers();
    echo "✅ Получено пользователей из базы: " . count($allUsers) . "\n\n";
    
    // Фильтрация пользователей с доступом (не гости)
    $validUsers = [];
    foreach ($allUsers as $user) {
        $userId = $user['user_id'];
        $userData = $user['data'];
        $accessLevel = $userData['access_level'] ?? 0;
        
        if ($accessLevel >= 1) { // Не гости
            $validUsers[] = [
                'user_id' => $userId,
                'fio' => $userData['fio'] ?? 'Неизвестный пользователь',
                'access_level' => $accessLevel
            ];
        }
    }
    
    echo "3. Анализ целевой аудитории:\n";
    echo "✅ Пользователей с доступом (уровень 1+): " . count($validUsers) . "\n";
    echo "✅ Исключено гостей (уровень 0): " . (count($allUsers) - count($validUsers)) . "\n\n";
    
    if (count($validUsers) > 0) {
        echo "4. Список получателей объявления:\n";
        foreach (array_slice($validUsers, 0, 10) as $index => $user) { // Показать первые 10
            echo "   " . ($index + 1) . ". {$user['fio']} (ID: {$user['user_id']}, Уровень: {$user['access_level']})\n";
        }
        if (count($validUsers) > 10) {
            echo "   ... и еще " . (count($validUsers) - 10) . " пользователей\n";
        }
        echo "\n";
        
        echo "5. ПОДТВЕРЖДЕНИЕ ОТПРАВКИ:\n";
        echo "===========================\n";
        echo "📢 ГОТОВО К ОТПРАВКЕ русского объявления " . count($validUsers) . " пользователям!\n\n";
        
        echo "⚠️  ВНИМАНИЕ: Это массовая рассылка!\n";
        echo "📝 Сообщение будет отправлено ВСЕМ пользователям с доступом\n";
        echo "🔒 Безопасность: пауза 0.1 сек между отправками\n\n";
        
        // РУЧНОЕ ПОДТВЕРЖДЕНИЕ
        echo "🚨 ТРЕБУЕТСЯ ПОДТВЕРЖДЕНИЕ:\n";
        echo "Для продолжения введите: yes\n";
        echo "Для отмены введите: no\n";
        echo "Ваш выбор: ";
        
        $handle = fopen("php://stdin", "r");
        $confirmation = trim(fgets($handle));
        fclose($handle);
        
        if (strtolower($confirmation) === 'yes') {
            echo "\n🚀 НАЧИНАЕМ ОТПРАВКУ РУССКОГО ОБЪЯВЛЕНИЯ!\n";
            echo "==========================================\n\n";
            
            $successCount = 0;
            $errorCount = 0;
            
            foreach ($validUsers as $index => $user) {
                $userId = $user['user_id'];
                $fio = $user['fio'];
                
                try {
                    echo "Отправка " . ($index + 1) . "/" . count($validUsers) . " -> {$fio} (ID: {$userId})... ";
                    
                    $result = $messageService->sendMessage($userId, $announcementMessage);
                    
                    if ($result && $result->isOk()) {
                        echo "✅ Успешно\n";
                        $successCount++;
                    } else {
                        echo "❌ Ошибка\n";
                        $errorCount++;
                    }
                    
                    // Пауза между отправками для безопасности
                    usleep(100000); // 0.1 секунды
                    
                } catch (Exception $e) {
                    echo "❌ Исключение: " . $e->getMessage() . "\n";
                    $errorCount++;
                }
            }
            
            echo "\n🎉 ОТПРАВКА РУССКОГО ОБЪЯВЛЕНИЯ ЗАВЕРШЕНА!\n";
            echo "==========================================\n";
            echo "✅ Успешно отправлено: {$successCount}\n";
            echo "❌ Ошибок: {$errorCount}\n";
            echo "📊 Общий охват: " . count($validUsers) . " российских пользователей\n\n";
            
            if ($successCount > 0) {
                echo "🎯 РЕЗУЛЬТАТ: Российские пользователи уведомлены о новом функционале!\n";
                echo "👥 Теперь они могут попробовать раздел 'Моя активность'\n";
                echo "🏆 Ожидайте роста активности и интереса к достижениям!\n";
            }
            
        } else {
            echo "\n❌ ОТПРАВКА ОТМЕНЕНА по вашему выбору\n";
            echo "Русское объявление НЕ отправлено пользователям.\n";
